#!/usr/bin/env python3
"""Rebuild the test fixtures from the saved raidres replies.

    python make_fixtures.py                 from the .json already here
    python make_fixtures.py --refresh REF   fetch event REF from the site first

The event is anonymised before it is saved -- character names, Discord user
ids, the author, the live event token and comments -- because this repository
is public and a raid list is other people's characters. The loot tables
(raid_*.json) hold nothing personal and are kept as served.

Writes:
    fixtures/event_DEMO42.json       the event, anonymised
    fixtures/expected.lua            what the watcher makes of it; test_http.lua
                                     holds the in-game conversion to this
    fixtures/RaidResBridge_data.lua  the watcher's reply file; test_bridge.lua
                                     reads it when there is no real one
"""

import io
import json
import os
import sys
import tempfile

import raidres_bridge as rb

HERE = os.path.dirname(os.path.abspath(__file__))
FIX = os.path.join(HERE, "fixtures")
REF = "DEMO42"
EVENT = os.path.join(FIX, "event_%s.json" % REF)
FAKE = ["Aldwyn", "Brisa", "Corvane", "Dagny", "Elowen", "Faelar", "Gorrim",
        "Hestia", "Ivor", "Jorunn", "Kestra", "Lumi", "Maren", "Nils", "Orla",
        "Perrin", "Quill", "Rosk", "Sefa", "Torvin"]


def scrub(event):
    """Anonymise an event. Running it twice changes nothing."""
    names, users = {}, {}
    for r in event.get("reservations", []):
        c = r.get("character") or {}
        if c.get("name"):
            if c["name"] not in names:
                n = len(names)
                names[c["name"]] = FAKE[n % len(FAKE)] + ("" if n < len(FAKE) else str(n))
            c["name"] = names[c["name"]]
        u = r.get("user") or {}
        if u.get("id"):
            users.setdefault(u["id"], str(1000 + len(users)))
            u["id"] = users[u["id"]]
        r["comment"] = None
    for h in event.get("advancedHrItems", []):
        h["characterNames"] = []
        h["note"] = None
    event.update(authorId="1000", eventHubToken="", forbiddenUserIds=[],
                 reference=REF)
    return event


if "--refresh" in sys.argv:
    real = rb.reference(sys.argv[sys.argv.index("--refresh") + 1])
    event = scrub(rb.get("/api/events/%s" % real))
    io.open(EVENT, "w", encoding="utf-8", newline="\n").write(
        json.dumps(event, ensure_ascii=False, separators=(",", ":")))
    print("saved %s as %s" % (real, REF))


def get(path):
    name = path.strip("/").split("/")[-1]
    if not name.endswith(".json"):
        name = "event_%s.json" % name
    return json.load(io.open(os.path.join(FIX, name), encoding="utf-8"))


rb.get = get
data, stats = rb.build(REF)

# fetch_raids and write_reply write files rather than returning anything, so
# let them write somewhere harmless and read the results back.
rb.RAID_SWEEP = [94, 100, 101]
rb.CUSTOM = tempfile.mkdtemp()
rb.fetch_raids()
raids = io.open(os.path.join(rb.CUSTOM, "RaidResBridge_raids.lua"), encoding="utf-8").read()
raids = raids.split("RaidResBridge_Raids = ", 1)[1]
reply = io.open(rb.write_reply(REF, data, stats), encoding="utf-8").read()

with io.open(os.path.join(FIX, "expected.lua"), "w", encoding="utf-8", newline="\n") as f:
    f.write("-- GENERATED by make_fixtures.py from the .json beside it -- do not edit.\n")
    f.write("Expected_Data = %s\n" % rb.lua_literal(data))
    f.write("Expected_Stats = %s\n" % rb.lua_literal(stats))
    f.write("Expected_Raids = %s" % raids)
io.open(os.path.join(FIX, rb.REPLY), "w", encoding="utf-8", newline="\n").write(reply)
print("wrote", os.path.join(FIX, "expected.lua"), "and", rb.REPLY)
